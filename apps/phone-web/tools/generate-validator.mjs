// Compiles the shared ItemDraft schema into a standalone validator at build time, so the browser needs no 'unsafe-eval'.
// The schema hash is embedded, and tests prove the result agrees with the runtime Ajv on the shared fixtures.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(appRoot, '../../packages/contracts/schema.json');
const outputPath = resolve(appRoot, 'shared/contracts/item-draft-validator.generated.js');

const schemaText = readFileSync(schemaPath, 'utf8');
const schema = JSON.parse(schemaText);
const schemaSha256 = createHash('sha256').update(schemaText).digest('hex');

const ajv = new Ajv2020({ strict: false, allErrors: true, code: { source: true, esm: true } });
ajv.addSchema(schema);
const validate = ajv.getSchema(`${schema.$id}#/$defs/ItemDraft`);
if (!validate) throw new Error('ItemDraft definition not found in schema');

// Ajv emits a CommonJS require for its code-point counter. Inlining the same semantics keeps the browser bundle free of Ajv
// and of CJS/ESM default-export differences between Node and the bundler. The equivalence test covers astral characters.
const RUNTIME_REQUIRE = /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/;
let code = standaloneCode(ajv, validate);
code = code.replace(RUNTIME_REQUIRE, 'const $1 = (text) => [...text].length;');
if (/\brequire\(/.test(code)) throw new Error('generated validator still contains require()');

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `// Generated by tools/generate-validator.mjs. Do not edit.\nexport const SCHEMA_SHA256 = "${schemaSha256}";\n${code}\n`);
console.log(JSON.stringify({ event: 'validator_generated', schemaSha256, outputPath }));
